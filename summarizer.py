import json
import os
import time
from groq import Groq
from dotenv import load_dotenv

load_dotenv()

client = Groq(api_key=os.environ["GROQ_API_KEY"])

PROMPT = """Ты — редактор новостного дайджеста про Уругвай для русскоязычной аудитории.
Прочитай текст на испанском и определи, что это за материал.

НОВОСТЬ — это событие, решение властей, происшествие, заявление, 
результат, скандал, изменение в законах, важное для жителей Уругвая 
или для понимания ситуации в стране. Это то, что произошло вчера 
или сегодня и что действительно стоит знать.

НЕ НОВОСТЬ (верни is_news: false) — это любой из следующих случаев:

1. ЛАЙФСТАЙЛ: советы, подборки, «как сделать», «сколько раз в день», 
   «какие продукты полезны», «как ухаживать за домом», рецепты, 
   психологические рекомендации без привязки к событию.

2. СВЕТСКАЯ ХРОНИКА: новости о знаменитостях, их отношениях, романах, 
   свадьбах, разводах, скандалах, слухах, опровержениях, «звёздных» 
   заявлениях, реакциях в соцсетях, нарядах, внешности. Сюда же — 
   любые заголовки со словами «опроверг(ла) слухи», «роман», «пара», 
   «бывший», «бывшая», «подтвердил(а) отношения».

3. СЕРВИСНЫЕ ИНСТРУКЦИИ: «как найти», «как узнать», «как проверить», 
   «где consultar», «cómo sacar», пошаговые руководства по бытовым 
   процедурам (получение документов, оплата счетов, поиск номера, 
   запись на приём). Это полезно, но это не новость дня.

4. ЛОКАЛЬНЫЕ МИКРОСОБЫТИЯ: школьные проекты, студенческие приложения, 
   мероприятия в маленьких городах, встречи общественных организаций, 
   локальные инициативы, не имеющие значения для страны в целом.

5. ОТРАСЛЕВЫЕ/УЗКИЕ НОВОСТИ: результаты аукционов скота, цены на 
   зерно, отчёты отраслевых ассоциаций, если это не влияет на 
   экономику страны в целом.

Если это НЕ НОВОСТЬ — верни JSON строго такого формата:
{{"is_news": false}}

Если это НОВОСТЬ — верни JSON:
{{
  "is_news": true,
  "title_ru": "краткий заголовок на русском (до 80 символов)",
  "summary_ru": "краткое описание на русском (2-3 предложения)",
  "tags": ["Политика", "Экономика"],
  "importance": 1-5
}}

Шкала importance:
5 — очень важно, касается всей страны, решение властей, крупное происшествие
4 — важно, заметное событие или решение
3 — средне, стоит упомянуть в дайджесте
2 — мелко, локально или узкоотраслевое
1 — незначительно, светская хроника, лайфстайл

Теги: Политика, Экономика, Общество, Международка, Здоровье, 
Образование, Наука, Суды, Безопасность, Экология.

Текст новости:
{text}
"""

def summarize(text: str, title: str) -> dict | None:
    text = text[:6000]

    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            messages=[{"role": "user", "content": PROMPT.format(text=text)}],
            temperature=0.3,
            response_format={"type": "json_object"},
        )

        data = json.loads(response.choices[0].message.content)

        if not data.get("is_news", True):
            return None

        return data
    except Exception as e:
        print(f"  ❌ LLM ошибка: {e}")
        return None

def deduplicate_summaries(summaries: list) -> list:
    """Просит LLM убрать дубликаты среди русских заголовков."""
    if len(summaries) < 2:
        return summaries

    titles_list = "\n".join(
        f"{i}. {s['summary']['title_ru']}"
        for i, s in enumerate(summaries)
    )

    prompt = f"""Ниже список заголовков новостей на русском языке.
Некоторые из них описывают одно и то же событие (дубликаты), 
даже если сформулированы по-разному.

Твоя задача: вернуть JSON-массив с индексами ТОЛЬКО тех новостей, 
которые стоит оставить. Из каждой группы дубликатов оставь один 
(самый полный или самый важный на твой взгляд).

Заголовки:
{titles_list}

Верни ответ строго в формате JSON: {{"keep": [0, 2, 5]}}
"""

    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.1,
            response_format={"type": "json_object"},
        )
        data = json.loads(response.choices[0].message.content)
        keep_indices = data.get("keep", list(range(len(summaries))))

        result = [summaries[i] for i in keep_indices if 0 <= i < len(summaries)]
        removed = len(summaries) - len(result)
        if removed:
            print(f"   LLM убрала {removed} дублей")
        return result
    except Exception as e:
        print(f"    Дедупликация не удалась: {e}. Оставляю как есть.")
        return summaries